"""
PilgrimAI - Agent State and Execution Tracing Infrastructure (Phase G)

Provides lightweight, strongly-typed contracts for agent lifecycle, routing decisions,
intermediate state management, chronological execution tracing, and standardized responses.

Core Principles:
- Zero external database or RAG dependencies.
- Zero LLM generation / API dependencies.
- Independent mutable defaults (zero cross-instance state bleeding).
- Chronological, non-negative, sanitized execution tracing.
"""

from typing import Dict, Any, List, Optional
from pydantic import BaseModel, Field, ConfigDict, field_validator


# Keys considered sensitive that must never leak into execution trace metadata
_SENSITIVE_METADATA_KEYS = {
    "api_key", "secret", "password", "token", "access_token",
    "auth", "authorization", "private_key", "credential"
}


def _sanitize_metadata(meta: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Sanitizes trace metadata by removing sensitive keys and guarding against
    raw document content flooding the trace.
    """
    if not meta:
        return {}

    sanitized = {}
    for k, v in meta.items():
        k_lower = str(k).lower()
        if any(sens in k_lower for sens in _SENSITIVE_METADATA_KEYS):
            sanitized[k] = "[REDACTED]"
        elif isinstance(v, str) and len(v) > 2000:
            # Truncate overly long text strings to prevent log bloat
            sanitized[k] = v[:2000] + "... [TRUNCATED]"
        else:
            sanitized[k] = v
    return sanitized


class ExecutionTrace(BaseModel):
    """
    In-memory trace record capturing an individual step or agent execution event.
    Preserves chronological execution history, latency metrics, and failure diagnostics.
    """
    model_config = ConfigDict(extra="allow")

    agent_name: str = Field(..., description="Name of the agent executing the step")
    step_name: str = Field(..., description="Identifier of the specific step or operation")
    status: str = Field(
        default="completed",
        description="Execution outcome: 'started', 'completed', 'failed', 'skipped'"
    )
    latency_ms: Optional[float] = Field(
        default=None,
        description="Elapsed execution time in milliseconds (non-negative)"
    )
    error: Optional[str] = Field(default=None, description="Error message if step failed")
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured step metadata for diagnostics"
    )

    @field_validator("latency_ms")
    @classmethod
    def validate_latency(cls, v: Optional[float]) -> Optional[float]:
        if v is not None:
            if v < 0:
                return 0.0
        return v


class AgentRouteDecision(BaseModel):
    """
    Data contract communicating routing outcomes from router logic to the coordinator.
    """
    model_config = ConfigDict(extra="allow")

    selected_agent: str = Field(..., description="Target specialist agent name")
    intent: str = Field(..., description="Classified intent (e.g., 'factual', 'list', 'compare', 'itinerary')")
    confidence: float = Field(default=1.0, description="Routing confidence score (0.0 to 1.0 or heuristic)")
    reason: str = Field(default="", description="Human-readable justification for the routing decision")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Additional context parameters extracted during routing")


class AgentResponse(BaseModel):
    """
    Standardized response payload produced by all specialist agents and aggregators.
    Designed for seamless downstream consumption and aggregation.
    """
    model_config = ConfigDict(extra="allow")

    success: bool = Field(default=True, description="Whether the agent completed its task without unhandled error")
    agent_name: str = Field(default="", description="Name of the responding agent")
    answer: str = Field(default="", description="Formatted answer text generated by the agent")
    sources: List[str] = Field(default_factory=list, description="List of source file paths or citations used")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Agent-specific structured data or metrics")
    error: Optional[str] = Field(default=None, description="Error description if success is False")
    latency_ms: Optional[float] = Field(default=None, description="Total execution latency in milliseconds")


class AgentState(BaseModel):
    """
    In-memory execution state passed through the agent coordinator and specialist agents.
    Tracks session identity, user query, routing outcomes, execution traces,
    intermediate results, and the synthesized final response.
    """
    model_config = ConfigDict(extra="allow")

    session_id: str = Field(default="default_session", description="Unique conversation session identifier")
    user_query: str = Field(default="", description="Original natural language query from the user")
    detected_intents: List[str] = Field(default_factory=list, description="Intents identified during query planning/routing")
    extracted_params: Dict[str, Any] = Field(default_factory=dict, description="Extracted parameters such as origin, destination, travel_mode")
    structured_constraints: Dict[str, Any] = Field(default_factory=dict, description="Structured constraints (duration_days, budget_limit, accommodation_required, temples, pax) extracted from query")
    active_agent: Optional[str] = Field(default=None, description="Name of the currently executing agent")
    intermediate_results: Dict[str, Any] = Field(default_factory=dict, description="Per-agent intermediate outputs keyed by agent name")
    final_response: Optional[AgentResponse] = Field(default=None, description="Synthesized final response payload")
    execution_trace: List[ExecutionTrace] = Field(default_factory=list, description="Chronological log of execution steps")

    def add_trace(
        self,
        agent_name: str,
        step_name: str,
        status: str = "completed",
        latency_ms: Optional[float] = None,
        error: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None
    ) -> ExecutionTrace:
        """
        Appends an execution trace entry to the state, preserving chronological order,
        enforcing non-negative latency, and sanitizing metadata.
        """
        safe_latency = max(0.0, latency_ms) if latency_ms is not None else None
        safe_meta = _sanitize_metadata(metadata)

        trace = ExecutionTrace(
            agent_name=agent_name,
            step_name=step_name,
            status=status,
            latency_ms=safe_latency,
            error=error,
            metadata=safe_meta
        )
        self.execution_trace.append(trace)
        return trace

    def get_trace(
        self,
        agent_name: Optional[str] = None,
        step_name: Optional[str] = None
    ) -> List[ExecutionTrace]:
        """
        Filters the chronological execution trace by agent name and/or step name.
        """
        traces = self.execution_trace
        if agent_name is not None:
            traces = [t for t in traces if t.agent_name == agent_name]
        if step_name is not None:
            traces = [t for t in traces if t.step_name == step_name]
        return traces

    def get_intermediate_result(self, agent_name: str, default: Any = None) -> Any:
        """
        Safely retrieves intermediate results stored for a specific agent.
        """
        return self.intermediate_results.get(agent_name, default)
